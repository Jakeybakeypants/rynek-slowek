#!/usr/bin/env node
// Writes src/js/01-frequency.js: the 1,000 most common Polish word forms, most common first.
// Source: FrequencyWords by Hermit Dave, built from OpenSubtitles 2018 (film and TV subtitles),
// https://github.com/hermitdave/FrequencyWords, content licensed CC BY-SA 4.0.
// Subtitles rank everyday spoken forms, which suits a game where each written form is its own word.
//
//   node tools/frequency.mjs              download the list and write the file
//   node tools/frequency.mjs list.txt     use a local copy of pl_50k.txt instead
import { readFileSync, writeFileSync } from "node:fs";

const SOURCE = "https://raw.githubusercontent.com/hermitdave/FrequencyWords/master/content/2018/pl/pl_50k.txt";
const TOP = 1000;
const text = process.argv[2] ? readFileSync(process.argv[2], "utf8") : await (await fetch(SOURCE)).text();
const words = [];
for (const line of text.split("\n")) {
  const w = line.split(" ")[0]?.trim().toLowerCase();
  // letters only, and drop "sie", which is się typed without the ogonek
  if (!w || !/^\p{L}+$/u.test(w) || w === "sie" || words.includes(w)) continue;
  words.push(w);
  if (words.length === TOP) break;
}
const out = `// The ${TOP} most common Polish word forms, most common first (rank = index + 1).
// Generated by tools/frequency.mjs from FrequencyWords by Hermit Dave (OpenSubtitles 2018),
// https://github.com/hermitdave/FrequencyWords, licensed CC BY-SA 4.0. Don't edit by hand.
const FREQ = ${JSON.stringify(words)};
const FREQ_RANK = new Map(FREQ.map((w, i) => [w, i + 1]));
`;
writeFileSync(new URL("../src/js/01-frequency.js", import.meta.url), out);
console.log(`Wrote ${words.length} words; first ten: ${words.slice(0, 10).join(", ")}`);
