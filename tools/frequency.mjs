#!/usr/bin/env node
// Writes src/js/01-frequency.js: for each language, its 3,000 most common word forms, most common first.
// Source: FrequencyWords by Hermit Dave, built from OpenSubtitles 2018 (film and TV subtitles),
// https://github.com/hermitdave/FrequencyWords, content licensed CC BY-SA 4.0.
// Subtitles rank everyday spoken forms, which suits a game where each written form is its own word.
// The lists are lower case (German nouns too); the game matches words in lower case.
//
//   node tools/frequency.mjs              download the lists and write the file
//   node tools/frequency.mjs DIR          use local copies DIR/<lang>_50k.txt instead
import { readFileSync, writeFileSync } from "node:fs";

const LANGS = ["pl", "de", "es", "fr"];
const SOURCE = lang => `https://raw.githubusercontent.com/hermitdave/FrequencyWords/master/content/2018/${lang}/${lang}_50k.txt`;
const TOP = 3000;
// left out: Polish "sie", typed without its accent in many subtitles, would push out the real word;
// the French ones are stray fragments of English and names
const SKIP = { pl: new Set(["sie"]), de: new Set(), es: new Set(), fr: new Set(["o'", "y'", "p'", "b'"]) };
// a word as each list writes it: letters only, except French elisions (c', qu') and hyphenated words (peut-être)
const WORD = { fr: /^(?:aujourd'hui|\p{L}+(?:-\p{L}+)*'?)$/u };
const lists = {};
for (const lang of LANGS) {
  const text = process.argv[2] ? readFileSync(`${process.argv[2]}/${lang}_50k.txt`, "utf8") : await (await fetch(SOURCE(lang))).text();
  const words = [], seen = new Set();
  // French subtitles often type œ as oe (coeur, soeur); keep only the proper spelling when the list has both
  const all = new Set(text.split("\n").map(l => l.split(" ")[0]?.trim().toLowerCase()));
  const dup = w => lang === "fr" && w.includes("oe") && all.has(w.replaceAll("oe", "œ"));
  for (const line of text.split("\n")) {
    const w = line.split(" ")[0]?.trim().toLowerCase();
    if (!w || !(WORD[lang] ?? /^\p{L}+$/u).test(w) || SKIP[lang].has(w) || dup(w) || seen.has(w)) continue;
    seen.add(w); words.push(w);
    if (words.length === TOP) break;
  }
  lists[lang] = words;
}
const out = `// The ${TOP} most common word forms of each language, most common first (rank = index + 1).
// Generated by tools/frequency.mjs from FrequencyWords by Hermit Dave (OpenSubtitles 2018),
// https://github.com/hermitdave/FrequencyWords, licensed CC BY-SA 4.0. Don't edit by hand.
const FREQ_BY_LANG = {
${LANGS.map(l => `  ${l}: ${JSON.stringify(lists[l])},`).join("\n")}
};
`;
writeFileSync(new URL("../src/js/01-frequency.js", import.meta.url), out);
for (const l of LANGS) console.log(`${l}: ${lists[l].length} words; first ten: ${lists[l].slice(0, 10).join(", ")}`);
